#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Типограф для русского текста страниц проектов.

Задача одна: убрать висячие предлоги, союзы и одинокие короткие слова
в конце строки. Делается на сборке, а не руками, поэтому работает
одинаково на всех страницах и не разъезжается при правке текста.

Что делаем:
  · неразрывный пробел после коротких предлогов и союзов
  · частицы «бы», «же», «ли» прилипают к слову слева
  · тире не начинает строку
  · число не отрывается от того, что считает: «2025 год», «5 лет»
  · последнее короткое слово абзаца не остаётся на строке одно

Разметку не трогаем: теги на время подменяются метками, поэтому
&nbsp; не может уехать в href или в alt. Ставим именно &nbsp;, а не
сам символ: в сгенерированном файле его видно, и правка не собьёт
невидимый пробел, который глазом не отличить от обычного.

Повторный прогон ничего не меняет: пробела на месте замены уже нет.
"""

import re

NB = '&nbsp;'

# Однобуквенные и двухбуквенные связываем всегда. Из трёхбуквенных берём
# только предлоги и союзы — «его» или «они» отрывать не запрещено.
SHORT3 = ('без для над под про изо обо ото как что чем или либо если хотя '
          'при чтоб').split()
LONG   = 'через около среди кроме между вместо''' .split()
PARTICLES = 'бы б же ж ли ль'.split()

_W = r'\wЀ-ӿ'
# \x00 — метка тега: после «на» может стоять <a>, связывать всё равно нужно
_AHEAD = r'(?=[«"(\[\x00]?[А-Яа-яЁёA-Za-z0-9\x00])'

_bind_after = re.compile(
    rf'(?<![{_W}])'
    r'([А-Яа-яЁёA-Za-z]{1,2}|' + '|'.join(SHORT3 + LONG) + r')'
    r' ' + _AHEAD, re.IGNORECASE)

_bind_before = re.compile(r' (' + '|'.join(PARTICLES) + rf')(?![{_W}])',
                          re.IGNORECASE)

_dash    = re.compile(r' (—|–)(?= )')
_number  = re.compile(r'(\d) (?=[А-Яа-яЁё%°])')
# Инициал — одна заглавная буква с точкой. Лукбехайнд обязателен:
# без него «развитие ИТ. Каждое» разбиралось как инициал «Т.»
_initial = re.compile(r'(?<![А-ЯЁа-яёA-Za-z])([А-ЯЁ]\.) (?=[А-ЯЁ])')
_abbrev  = re.compile(r'\b(г|ул|д|стр|рис|табл|им|тыс|млн|млрд)\. ')
# последнее слово абзаца: короткое не оставляем на строке одно
_orphan  = re.compile(r'(\S) (\S{1,7})(\s*)$')


def typo(s):
    if not s:
        return s
    tags = []

    def hide(m):
        tags.append(m.group(0))
        return '\x00%d\x00' % (len(tags) - 1)

    s = re.sub(r'<[^>]*>', hide, s)

    s = _bind_after.sub(lambda m: m.group(1) + NB, s)
    s = _bind_before.sub(lambda m: NB + m.group(1), s)
    s = _dash.sub(lambda m: NB + m.group(1), s)
    s = _number.sub(lambda m: m.group(1) + NB, s)
    s = _initial.sub(lambda m: m.group(1) + NB, s)
    s = _abbrev.sub(lambda m: m.group(1) + '.' + NB, s)
    s = _orphan.sub(lambda m: m.group(1) + NB + m.group(2) + m.group(3), s)

    return re.sub(r'\x00(\d+)\x00', lambda m: tags[int(m.group(1))], s)


if __name__ == '__main__':
    N = ' '   # для проверок: сравниваем с текстом, где стоит сам символ
    def t(s): return typo(s).replace(NB, N)

    checks = [
        ('Центр работает с промышленностью, и визуальный язык взят оттуда.',
         ['с' + N + 'промышленностью', 'и' + N + 'визуальный']),
        ('Сайт должен говорить с тремя аудиториями — и не сорваться.',
         ['аудиториями' + N + '—', 'и' + N + 'не' + N + 'сорваться']),
        ('Отраслевой центр при МГТУ «СТАНКИН», созданный в 2025 году.',
         ['при' + N + 'МГТУ', '2025' + N + 'году', 'в' + N + '2025']),
        ('Сделали бы иначе, если бы знали.', ['бы' + N + 'иначе', 'если' + N + 'бы']),
        ('Работает и на сайте, и в документах, и на стендах.',
         ['и' + N + 'на' + N + 'стендах']),
        # разметка остаётся нетронутой
        ('<a href="ohmy-case-gck.html" title="а б в">я и он</a>',
         ['title="а б в"', 'я' + N + 'и' + N + 'он']),
        # связка работает и через тег
        ('Ссылка на <em>сайт</em> живёт тут.', ['на' + N + '<em>']),
    ]
    bad = 0
    for src, want in checks:
        got = t(src)
        for w in want:
            if w not in got:
                print('  ПРОВАЛ:', repr(w), '→', repr(got)); bad += 1

    # висячее слово: короткое приклеиваем, длинное оставляем
    assert t('Логотип и стиль работают за пределами сайта и на стендах.') \
        .endswith('на' + N + 'стендах.'), t('… и на стендах.')
    a = t('Стиль одинаково держится в документах и на площадках мероприятий.')
    assert a.endswith('площадках' + N + 'мероприятий.') is False, a[-30:]

    # повторный прогон ничего не меняет
    s = 'и в доме — с ним, если бы. 5 лет, г. Москва.'
    assert typo(typo(s)) == typo(s)

    # неразрывных пробелов не должно быть внутри тегов
    out = typo('<img src="a b.jpg" alt="я и он"> и текст')
    assert 'alt="я и он"' in out and NB not in out.split('>')[0], out

    print('типограф: проверки пройдены' if not bad else f'типограф: провалов {bad}')
